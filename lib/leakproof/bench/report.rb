# frozen_string_literal: true

require "json"

module Leakproof
  module Bench
    # Writes the summary. Never hand-edited, so the published numbers and the
    # measured numbers cannot drift apart.
    class Report
      SCHEMA = "leakproof/bench-result-v1"

      def initialize(result)
        @result = result
      end

      def to_json(*)
        JSON.pretty_generate({ schema: SCHEMA, version: Leakproof::VERSION }.merge(@result))
      end

      def to_markdown
        [header, confusion, reduction, per_rule, misses].compact.join("\n")
      end

      private

      def filtered = @result[:filtered]
      def unfiltered = @result[:unfiltered]

      def header
        <<~TEXT
          # Benchmark summary

          Generated by `leakproof-bench`. Do not edit by hand.

          Corpus: #{@result[:planted]} planted credentials, #{@result[:decoys]} decoys, seed #{@result[:seed]}.
        TEXT
      end

      def confusion
        <<~TEXT

          ## Confusion matrix

          | | reported | not reported |
          |---|---|---|
          | credential present in source | #{filtered[:true_positives]} | #{filtered[:false_negatives]} |
          | no credential present | #{filtered[:false_positives]} | n/a |

          Precision #{percent(filtered[:precision])}, recall #{percent(filtered[:recall])} over
          #{filtered[:must_find]} credentials planted in source or removed from it.
          #{filtered[:confirmed]} reached the confirmed tier.

          Two populations are graded apart from the matrix, because reporting them
          would be the error:

          - credentials under a fixture or documentation path, correctly demoted:
            #{filtered[:demoted]}
          - types that are public by design, and advisory rules that must not
            surface on their own evidence, correctly ignored:
            #{filtered[:public_types_ignored]}
        TEXT
      end

      def reduction
        <<~TEXT

          ## What the context filter removes

          | | findings reported | false positives |
          |---|---|---|
          | without the filter | #{unfiltered[:reported]} | #{unfiltered[:false_positives]} |
          | with the filter | #{filtered[:reported]} | #{filtered[:false_positives]} |
        TEXT
      end

      def per_rule
        rows = filtered[:by_rule].sort.map do |rule, stats|
          "| `#{rule}` | #{stats[:planted]} | #{stats[:found]} | #{percent(stats[:recall])} |"
        end
        <<~TEXT

          ## Recall by rule

          | rule | planted | found | recall |
          |---|---|---|---|
          #{rows.join("\n")}
        TEXT
      end

      def misses
        return "\n## What it missed\n\nNothing planted went unreported.\n" if filtered[:missed].empty?

        rows = filtered[:missed].map { |m| "| `#{m[:rule]}` | #{m[:path]} | #{m[:placement]} |" }
        <<~TEXT

          ## What it missed

          | rule | path | placement |
          |---|---|---|
          #{rows.join("\n")}
        TEXT
      end

      def percent(value)
        value.nil? ? "n/a" : "#{(value * 100).round(1)}%"
      end
    end
  end
end
